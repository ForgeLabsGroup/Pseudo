import { runPersonaAgent } from '@pseudo/agents';
import { getAdminClient } from '@pseudo/database';
import type { PersonaIdentity } from '@pseudo/shared';
import { publish } from '../lib/bus';
import type { RunCtx } from '../lib/runs';
import { ensurePlaybook } from './research';

/** Workflow A: Persona Agent -> validate -> save identity as a new version. */
export async function personaJob(
  ctx: RunCtx,
  personaId: string,
  input: {
    description: string;
    instructions?: string;
    existing?: PersonaIdentity;
    archetypeId?: string | null;
  },
) {
  const admin = getAdminClient();
  try {
    const playbook = input.archetypeId ? await ensurePlaybook(ctx, input.archetypeId) : undefined;
    const { identity, meta } = await runPersonaAgent({ ...input, playbook }, ctx.progress);
    await ctx.progress('save', 'Saving identity as a new version');
    await saveIdentityVersion(
      ctx.userId,
      personaId,
      identity,
      input.existing ? 'Regenerated by Persona Agent' : 'Generated by Persona Agent',
      'draft',
    );
    publish(ctx.userId, { type: 'persona.updated', personaId });
    return { output: { identity }, ...meta };
  } catch (err) {
    if (!input.existing)
      await admin.from('personas').update({ status: 'failed' }).eq('id', personaId);
    publish(ctx.userId, { type: 'persona.updated', personaId });
    throw err;
  }
}

/** Never overwrites history: bumps current_version and appends to persona_versions. */
export async function saveIdentityVersion(
  userId: string,
  personaId: string,
  identity: PersonaIdentity,
  changeNote: string | null,
  status?: string,
) {
  const admin = getAdminClient();
  const { data: p, error } = await admin
    .from('personas')
    .select('current_version')
    .eq('id', personaId)
    .single();
  if (error) throw new Error(error.message);
  const version = (p.current_version as number) + 1;
  const ins = await admin
    .from('persona_versions')
    .insert({ user_id: userId, persona_id: personaId, version, identity, change_note: changeNote });
  if (ins.error) throw new Error(ins.error.message);
  const upd = await admin
    .from('personas')
    .update({
      identity,
      name: identity.name,
      handle: identity.handle,
      tagline: identity.tagline,
      current_version: version,
      ...(status ? { status } : {}),
    })
    .eq('id', personaId);
  if (upd.error) throw new Error(upd.error.message);
  return version;
}
